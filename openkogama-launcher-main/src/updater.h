#ifndef UPDATER_H
#define UPDATER_H

class QWidget;

// Обновление лаунчера.
//
// Два режима в одном месте:
//  - лаунчер, установленный Velopack, обновляет их штатный механизм;
//  - портативный zip (то, чем делятся друзья) обновляет себя сам: качает
//    zip с релиза, распаковывает и заменяет файлы после своего закрытия.
//
// Проверка идёт по публичному API GitHub, без токена в билде.
namespace Updater {

// Вызывается первым делом в main: если запущен процесс самозамены
// (--apply-update), он дожидается закрытия старого лаунчера, копирует
// файлы на место и перезапускает приложение. Возвращает true, если
// процесс уже отработал и main должен выйти.
bool applyIfNeeded(int &argc, char **argv);

void startup();
void check(QWidget *window);

// Текущая версия лаунчера, зашитая в exe.
const char *version();

}

#endif // UPDATER_H
